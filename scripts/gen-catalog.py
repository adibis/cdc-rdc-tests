#!/usr/bin/env python3
"""Regenerate docs/catalog.md and the case counts in README.md and
docs/attributes.md from the case manifests. Run before commit.

With --check, write nothing and exit 1 if any of them is stale, or if a
README results row is scored out of a different number of cases.
"""
import glob
import json
import os
import re
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def loc(e):
    if "line" in e:
        return f"line {e['line']}"
    if "dst" in e:
        return f"dst {e['dst']}"
    return "unlocated"


# Waiver spellings docs/attributes.md documents, aliases included.
WAIVERS = re.compile(r"\(\*\s*(cdc_sync|synchronizer|async_reg|cdc_static|"
                     r"quasi_static|cdc_handshake|cdc_gray|reset_polarity|"
                     r"reset_sync|reset_synchronizer|glitchless_clock_mux|"
                     r"glitchless_mux|glitchfree_clock_mux|scan_en)\b",
                     re.IGNORECASE)

cases = []
attr_cases = 0
for mf in glob.glob(os.path.join(ROOT, "cases", "tier*", "*", "manifest.json")):
    try:
        m = json.load(open(mf))
        sv = open(os.path.join(os.path.dirname(mf), m["design"])).read()
    except (json.JSONDecodeError, OSError, UnicodeDecodeError, KeyError) as e:
        sys.exit(f"gen-catalog: bad case {mf}: {e}")
    cases.append(m)
    attr_cases += bool(WAIVERS.search(sv))

tiers = defaultdict(list)
for m in cases:
    tiers[m.get("tier", 1)].append(m)

out = ["# Case catalog", "",
       "Each firing case names the rule and the source line (or",
       "destination name for port findings) where the violation",
       "must report; silence cases must report nothing. Findings",
       "marked note are informational records; `--ignore-notes`",
       "drops them on both sides for violation-oriented checkers.",
       "Regenerated by `scripts/gen-catalog.py` — do not edit by hand.", ""]
for tier in sorted(tiers):
    ms = sorted(tiers[tier], key=lambda m: m["id"])
    by_rule = defaultdict(list)
    silent = []
    for m in ms:
        if not m["expect"]:
            silent.append(m)
        seen = set()
        for e in m["expect"]:
            if e["rule"] not in seen:
                by_rule[e["rule"]].append(m)
                seen.add(e["rule"])
    out.append(f"## Tier {tier} ({len(ms)} cases)")
    out.append("")
    for rule in sorted(by_rule):
        rs = by_rule[rule]
        out.append(f"### {rule} ({len(rs)} firing)")
        out.append("")
        for m in rs:
            parts = []
            for e in m["expect"]:
                if e["rule"] != rule:
                    continue
                s = f"{loc(e)}"
                if e.get("severity") == "note":
                    s += " [note]"
                parts.append(s)
            out.append(f"- `{m['id']}` ({', '.join(parts)}): {m.get('notes', '')}")
        out.append("")
    out.append(f"### Silence ({len(silent)} cases)")
    out.append("")
    for m in silent:
        out.append(f"- `{m['id']}`: {m.get('notes', '')}")
    out.append("")


def is_note(e):
    return e.get("severity") == "note"


def stats_block():
    n = len(cases)
    rules = {e["rule"] for m in cases for e in m["expect"]}
    note_rules = rules - {e["rule"] for m in cases for e in m["expect"] if not is_note(e)}
    violation = sum(1 for m in cases if any(not is_note(e) for e in m["expect"]))
    note_only = sum(1 for m in cases if m["expect"] and all(is_note(e) for e in m["expect"]))
    silent = sum(1 for m in cases if not m["expect"])
    findings = sum(len(m["expect"]) for m in cases)
    notes = sum(1 for m in cases for e in m["expect"] if is_note(e))
    where = f"Tier {sorted(tiers)[0]}" if len(tiers) == 1 else "The suite"
    only = ""
    if note_rules:
        only = (f" ({', '.join(sorted(note_rules))} only "
                f"{'records' if len(note_rules) == 1 else 'record'} notes)")
    return "\n".join([
        f"{where} holds {n} cases covering {len(rules)} rules{only}, with "
        f"{findings} expected findings: {findings - notes} violations "
        f"(errors and warnings) and {notes} notes. {n - silent} cases have a "
        f"nonempty oracle:",
        "",
        f"- **{violation} violation cases** expect at least one error or "
        "warning at a given location, and may also expect notes.",
        f"- **{note_only} note-only cases** expect informational records and "
        "nothing else; under `--ignore-notes` they must be silent.",
        "",
        f"The other {silent} are **silence cases**: they plant the approved "
        "pattern (a two-flop synchronizer, a gray-coded bus, a locally "
        "synchronized reset) and must report nothing.",
    ])


def splice(path, begin, end, body):
    text = open(path).read()
    pat = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.DOTALL)
    if len(pat.findall(text)) != 1:
        sys.exit(f"gen-catalog: {os.path.relpath(path, ROOT)} needs exactly one {begin} ... {end}")
    return pat.sub(lambda _: begin + body + end, text)


readme = os.path.join(ROOT, "README.md")
attrs = os.path.join(ROOT, "docs", "attributes.md")
want = {
    os.path.join(ROOT, "docs", "catalog.md"): "\n".join(out),
    readme: splice(readme, "<!-- stats:begin (generated by scripts/gen-catalog.py; do not edit) -->\n",
                   "\n<!-- stats:end -->", stats_block()),
    attrs: splice(attrs, "<!-- stats:attr -->", "<!-- /stats:attr -->", str(attr_cases)),
}

errors = []
for row in re.findall(r"^\|[^|\n]+\|[^|\n]+\|([^|\n]+)\|([^|\n]+)\|$", want[readme], re.MULTILINE):
    for cell in row:
        score = re.fullmatch(r"\s*\d+ / (\d+)\s*", cell)
        if score and int(score.group(1)) != len(cases):
            errors.append(f"README.md: results row scored out of {score.group(1)}, "
                          f"but the suite has {len(cases)} cases; rerun the checker")

if "--check" in sys.argv[1:]:
    for path, text in want.items():
        if open(path).read() != text:
            errors.append(f"{os.path.relpath(path, ROOT)} is stale; run scripts/gen-catalog.py")
else:
    for path, text in want.items():
        open(path, "w").write(text)
    print(f"catalog: {len(cases)} cases across tiers {sorted(tiers)}")
for e in dict.fromkeys(errors):
    print(f"gen-catalog: {e}", file=sys.stderr)
sys.exit(1 if errors else 0)
