#!/usr/bin/env python3
"""Regenerate docs/catalog.md from case manifests. Run before commit."""
import glob
import json
import os
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cases = []
for mf in glob.glob(os.path.join(ROOT, "cases", "tier1", "*", "manifest.json")):
    cases.append(json.load(open(mf)))

by_rule = defaultdict(list)
silent = []
for m in sorted(cases, key=lambda m: m["id"]):
    if not m["expect"]:
        silent.append(m)
    seen = set()
    for e in m["expect"]:
        if e["rule"] not in seen:
            by_rule[e["rule"]].append(m)
            seen.add(e["rule"])

out = ["# Tier-1 case catalog", "",
       f"{len(cases)} cases. Each firing case names the rule and the source",
       "line (or destination name for port findings) where the violation",
       "must report; silence cases must report nothing. Regenerated by",
       "`scripts/gen-catalog.py` — do not edit by hand.", ""]
for rule in sorted(by_rule):
    ms = by_rule[rule]
    out.append(f"## {rule} ({len(ms)} firing)")
    out.append("")
    for m in ms:
        locs = ", ".join(f"line {e['line']}" if "line" in e else f"dst {e['dst']}"
                         for e in m["expect"] if e["rule"] == rule)
        out.append(f"- `{m['id']}` ({locs}): {m.get('notes', '')}")
    out.append("")
out.append(f"## Silence ({len(silent)} cases)")
out.append("")
for m in silent:
    out.append(f"- `{m['id']}`: {m.get('notes', '')}")
out.append("")
open(os.path.join(ROOT, "docs", "catalog.md"), "w").write("\n".join(out))
print(f"catalog: {len(cases)} cases, {len(by_rule)} rules, {len(silent)} silence")
