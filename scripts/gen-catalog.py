#!/usr/bin/env python3
"""Regenerate docs/catalog.md from case manifests. Run before commit."""
import glob
import json
import os
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def loc(e):
    if "line" in e:
        return f"line {e['line']}"
    if "dst" in e:
        return f"dst {e['dst']}"
    return "unlocated"


cases = []
for mf in glob.glob(os.path.join(ROOT, "cases", "tier*", "*", "manifest.json")):
    try:
        cases.append(json.load(open(mf)))
    except (json.JSONDecodeError, OSError, UnicodeDecodeError) as e:
        sys.exit(f"gen-catalog: bad manifest {mf}: {e}")

tiers = defaultdict(list)
for m in cases:
    tiers[m.get("tier", 1)].append(m)

out = ["# Case catalog", "",
       "Each firing case names the rule and the source line (or",
       "destination name for port findings) where the violation",
       "must report; silence cases must report nothing. Findings",
       "marked note are informational records; `--ignore-notes`",
       "drops them on both sides for violation-oriented checkers.",
       "Regenerated by `scripts/gen-catalog.py` — do not edit by hand.", ""]
for tier in sorted(tiers):
    ms = sorted(tiers[tier], key=lambda m: m["id"])
    by_rule = defaultdict(list)
    silent = []
    for m in ms:
        if not m["expect"]:
            silent.append(m)
        seen = set()
        for e in m["expect"]:
            if e["rule"] not in seen:
                by_rule[e["rule"]].append(m)
                seen.add(e["rule"])
    out.append(f"## Tier {tier} ({len(ms)} cases)")
    out.append("")
    for rule in sorted(by_rule):
        rs = by_rule[rule]
        out.append(f"### {rule} ({len(rs)} firing)")
        out.append("")
        for m in rs:
            parts = []
            for e in m["expect"]:
                if e["rule"] != rule:
                    continue
                s = f"{loc(e)}"
                if e.get("severity") == "note":
                    s += " [note]"
                parts.append(s)
            out.append(f"- `{m['id']}` ({', '.join(parts)}): {m.get('notes', '')}")
        out.append("")
    out.append(f"### Silence ({len(silent)} cases)")
    out.append("")
    for m in silent:
        out.append(f"- `{m['id']}`: {m.get('notes', '')}")
    out.append("")
open(os.path.join(ROOT, "docs", "catalog.md"), "w").write("\n".join(out))
print(f"catalog: {len(cases)} cases across tiers {sorted(tiers)}")
